#!/usr/bin/env python3
"""Tests for the weekly-sync tooling: the generated scoped-rules block (migrate_v3 / migrate_v4) and the
drift lists harness-health reports. Run: python3 tools/test_harness_sync.py

Two incidents these pin:
  * `migrate_v3 --profile platform` skipped the rules scan and rewrote every non-Go repo's
    `harness:scoped-rules` table EMPTY, although its `.claude/rules/*.md` declared `paths:`; the weekly
    sync would have wiped the tables the parity PRs filled. migrate_v4 did not write the block at all.
  * harness-health only compared migrate_v3's MANAGED list, so a repo whose INCIDENTS.md, review
    subagents or test_red_issue.py (migrate_v4's V4_MANAGED) drifted showed as in sync.
"""
from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

TPL = Path(__file__).resolve().parent.parent
V3 = TPL / "tools" / "migrate_v3.py"
V4 = TPL / "tools" / "migrate_v4.py"

SCOPED = '---\npaths:\n  - "src/lib/**"\n  - "src/pwa/**"\n---\n\n# Offline outbox\n'
INLINE = '---\npaths: ["terraform/**/*.tf", \'helm-values/**\']\n---\n\n# Terraform wiring\n'
COL0 = '---\ndescription: edge rules\npaths:\n- "charts/**"\n- scripts/** # comment\n---\n\n# Edge\n'
PLAIN = "# Always-on rule\n"
OLD_EMPTY_BLOCK = (
    "<!-- harness:scoped-rules:start (generated by tools/migrate_v3.py in warehouse-harness-template; "
    "do not hand-edit) -->\n## Scoped rules and harness\n\nClaude Code loads each rule below automatically when "
    "you touch the matching paths.\n<!-- harness:scoped-rules:end -->\n"
)


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


class Fixture:
    def __init__(self, go: bool, rules: dict[str, str], claude: str = "# svc\n\nIntro.\n"):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        git(self.root, "init", "-q")
        if go:
            (self.root / "go.mod").write_text("module example.com/svc\n\ngo 1.27\n")
        (self.root / ".claude" / "rules").mkdir(parents=True)
        for name, text in rules.items():
            (self.root / ".claude" / "rules" / name).write_text(text)
        (self.root / "CLAUDE.md").write_text(claude)
        os.symlink("CLAUDE.md", self.root / "AGENTS.md")

    def run(self, script: Path, *args: str) -> str:
        r = subprocess.run([sys.executable, str(script), "--repo", str(self.root), "--template", str(TPL), *args],
                           capture_output=True, text=True)
        assert r.returncode == 0, r.stderr + r.stdout
        return r.stdout

    def claude(self) -> str:
        return (self.root / "CLAUDE.md").read_text()

    def block(self) -> str:
        t = self.claude()
        return t[t.index("<!-- harness:scoped-rules:start"):t.index("<!-- harness:scoped-rules:end -->")]

    def close(self):
        self.tmp.cleanup()


class ScopedRulesBlock(unittest.TestCase):
    def setUp(self):
        self.fx = []

    def tearDown(self):
        for f in self.fx:
            f.close()

    def fixture(self, *a, **k) -> Fixture:
        f = Fixture(*a, **k)
        self.fx.append(f)
        return f

    def test_platform_profile_lists_rules_that_declare_paths(self):
        f = self.fixture(go=False, rules={"offline-outbox.md": SCOPED, "plain.md": PLAIN})
        f.run(V3, "--profile", "platform", "--fast-deps", "lint")
        block = f.block()
        self.assertIn("| When touching | Read |", block, "platform profile wrote an EMPTY scoped-rules table")
        self.assertIn("| `src/lib/**`, `src/pwa/**` | `.claude/rules/offline-outbox.md` |", block)
        self.assertNotIn("plain.md", block, "a rule without `paths:` is always-on, not scoped")
        second = f.run(V3, "--profile", "platform", "--fast-deps", "lint", "--dry-run")
        self.assertNotIn("CLAUDE.md", second, "regenerating the block is not idempotent")

    def test_platform_profile_never_invents_scoping(self):
        # rest-api.md has a Go-service default in RULE_PATHS; a platform repo must keep it untouched
        f = self.fixture(go=False, rules={"rest-api.md": PLAIN})
        f.run(V3, "--profile", "platform")
        self.assertEqual((f.root / ".claude/rules/rest-api.md").read_text(), PLAIN)
        self.assertNotIn("rest-api.md", f.block())

    def test_inline_and_unindented_paths_are_parsed(self):
        f = self.fixture(go=False, rules={"tf.md": INLINE, "edge.md": COL0})
        f.run(V3, "--profile", "platform")
        block = f.block()
        self.assertIn("| `terraform/**/*.tf`, `helm-values/**` | `.claude/rules/tf.md` |", block)
        self.assertIn("| `charts/**`, `scripts/**` | `.claude/rules/edge.md` |", block)

    def test_service_profile_still_scopes_known_rules(self):
        f = self.fixture(go=True, rules={"rest-api.md": PLAIN, "domain-model.md": PLAIN})
        f.run(V3)
        self.assertTrue((f.root / ".claude/rules/rest-api.md").read_text().startswith("---\npaths:\n"))
        self.assertIn("`.claude/rules/rest-api.md`", f.block())
        self.assertNotIn("domain-model.md", f.block())

    def test_v4_repairs_an_empty_table_in_both_profiles(self):
        for go in (False, True):
            with self.subTest(go=go):
                f = self.fixture(go=go, rules={"offline-outbox.md": SCOPED},
                                 claude="# repo\n\nIntro.\n\n" + OLD_EMPTY_BLOCK)
                f.run(V4)
                self.assertIn("| `src/lib/**`, `src/pwa/**` | `.claude/rules/offline-outbox.md` |", f.block(),
                              "migrate_v4 left the empty scoped-rules table in place")
                self.assertIn("Intro.", f.claude())
                self.assertNotIn("CLAUDE.md", f.run(V4, "--dry-run"), "migrate_v4 block is not idempotent")

    def test_v4_appends_the_block_when_missing(self):
        f = self.fixture(go=False, rules={"offline-outbox.md": SCOPED})
        f.run(V4)
        self.assertIn("`.claude/rules/offline-outbox.md`", f.block())


class FleetRulesNamespace(unittest.TestCase):
    """The template carries the WAREHOUSE fleet rule set only; a retail-network repo's CloudEvents rule is its own
    variant (warehouse-docs agents/retailnetwork/). A fleet-wide sync would have overwritten it with the warehouse one."""

    RETAIL = ("---\npaths:\n  - \"apis/asyncapi*\"\n---\n\n# Rule: CloudEvents 1.0 on every Kafka message (retail network)\n\n"
              "- `type` = `com.retailnetwork.<tier>.<context>.<entity>.<Event>`\n")

    def make(self, cloudevents):
        f = Fixture(go=True, rules={})
        self.addCleanup(f.close)
        fleet = f.root / ".claude" / "rules" / "fleet"
        fleet.mkdir(parents=True)
        (fleet / "cloudevents.md").write_text(cloudevents)
        return f

    def test_retailnetwork_cloudevents_rule_is_kept(self):
        f = self.make(self.RETAIL)
        f.run(V3)
        self.assertEqual((f.root / ".claude/rules/fleet/cloudevents.md").read_text(), self.RETAIL,
                         "migrate_v3 replaced the retail-network CloudEvents rule with the warehouse one")
        shared = TPL / ".claude/rules/fleet/no-auth-and-mcp.md"
        self.assertEqual((f.root / ".claude/rules/fleet/no-auth-and-mcp.md").read_bytes(), shared.read_bytes(),
                         "namespace-neutral fleet rules must still be synced")

    def test_warehouse_cloudevents_rule_is_synced(self):
        f = self.make("---\npaths:\n  - \"apis/asyncapi*\"\n---\n\n# Fleet rule: CloudEvents (old copy)\n")
        f.run(V3)
        self.assertEqual((f.root / ".claude/rules/fleet/cloudevents.md").read_bytes(),
                         (TPL / ".claude/rules/fleet/cloudevents.md").read_bytes())


class CrossRepoRuleLinks(unittest.TestCase):
    """migrate_v3's ref rewrite maps a generic skill's `.claude/rules/mfe-remotes.md` to the repo's own frontend
    rule. product-master's how-to-add-a-frontend-remote skill cites warehouse-console's mfe-remotes rule ("see that
    repo's ..."): the rewrite turned it into a link to product-master's frontend.md, a different rule. A link to
    ANOTHER repo's rule must be left alone; only a bare (local) link is rewritten."""

    SKILL = ("# Adding a frontend remote\n\n"
             "This is the layer that `warehouse-console` (the shell) lazy-loads — see that repo's\n"
             "`.claude/rules/mfe-remotes.md` for the shell-side half of this contract.\n"
             "Also warehouse-console's `.claude/rules/mfe-remotes.md`, and\n"
             "`warehouse-console/.claude/rules/mfe-remotes.md`, and IQVO/warehouse-console:.claude/rules/mfe-remotes.md.\n"
             "The boundary lives in the sibling repository's `.claude/rules/bounded-context-boundary.md`.\n"
             "LOCAL: read `.claude/rules/mfe-remotes.md` and this repo's `.claude/rules/bounded-context-boundary.md`.\n")

    def run_v3(self):
        f = Fixture(go=True, rules={"frontend.md": PLAIN, "domain-model.md": PLAIN})
        self.addCleanup(f.close)
        skill = f.root / ".claude" / "skills" / "how-to-add-a-frontend-remote" / "SKILL.md"
        skill.parent.mkdir(parents=True)
        skill.write_text(self.SKILL)
        f.run(V3)
        return f, skill.read_text()

    def test_links_to_another_repos_rule_are_left_alone(self):
        _, text = self.run_v3()
        cross = text.split("LOCAL:")[0]
        self.assertEqual(cross, self.SKILL.split("LOCAL:")[0],
                         "migrate_v3 rewrote a link to ANOTHER repo's rule into a local rule")

    def test_local_links_are_still_rewritten(self):
        f, text = self.run_v3()
        local = text.split("LOCAL:")[1]
        self.assertIn("`.claude/rules/frontend.md`", local)
        self.assertIn("this repo's `.claude/rules/domain-model.md`", local)
        self.assertNotIn("refs rewritten", f.run(V3, "--dry-run"), "the ref rewrite is not idempotent")


class TemplateCarriesItsOwnMigrations(unittest.TestCase):
    """The template's ci.yml.template / Makefile are what a new scaffold starts from. They lagged behind what
    migrate_v3/v4 add to every repo: the guide-lint job ran neither repo_lint.py nor test_repo_lint.py, so the
    'repo_lint R11 (guide-lint job)' comment in the scaffold's own test job was false on day one."""

    def test_migrations_are_a_no_op_on_the_template(self):
        for script in (V3, V4):
            with self.subTest(script=script.name):
                r = subprocess.run([sys.executable, str(script), "--repo", str(TPL), "--template", str(TPL),
                                    "--dry-run"], capture_output=True, text=True)
                self.assertEqual(r.returncode, 0, r.stderr)
                self.assertEqual(r.stdout.strip(), "", f"{script.name} would still change the template itself")

    def test_guide_lint_job_runs_repo_lint_and_its_tests(self):
        v3 = load("migrate_v3_for_test", V3)
        lines = (TPL / ".github/workflows/ci.yml.template").read_text().splitlines()
        b = v3.Migrator._job_bounds(lines, "guide-lint")
        self.assertTrue(b, "ci.yml.template has no guide-lint job")
        job = "\n".join(lines[b[0]:b[1]])
        for step in ("guide_lint.py", "repo_lint.py", "test_repo_lint.py", "test_hook.py", "test_red_issue.py"):
            self.assertIn(f"python3 scripts/harness/{step}", job, f"the guide-lint job does not run {step}")


class HealthDriftLists(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.health = load("harness_health", TPL / "scripts" / "harness-health.py")

    def test_managed_list_includes_v4_managed(self):
        v4 = load("migrate_v4_for_test", V4)
        got = set(self.health.managed_list())
        missing = [r for r in v4.V4_MANAGED if r not in got]
        self.assertEqual(missing, [], "harness-health ignores migrate_v4's V4_MANAGED files")

    def test_drifted_or_missing_incidents_is_reported(self):
        with tempfile.TemporaryDirectory() as d:
            repo = Path(d)
            git(repo, "init", "-q")
            git(repo, "config", "user.email", "t@example.com")
            git(repo, "config", "user.name", "t")
            (repo / "README.md").write_text("x\n")
            git(repo, "add", "-A")
            git(repo, "commit", "-qm", "init")
            git(repo, "update-ref", "refs/remotes/origin/develop", "HEAD")
            files = set(git(repo, "ls-tree", "-r", "--name-only", "origin/develop").split())
            self.assertIn("INCIDENTS.md (missing)", self.health.managed_drift(repo, files))

            (repo / "INCIDENTS.md").write_text("# a forked incident log\n")
            git(repo, "add", "-A")
            git(repo, "commit", "-qm", "fork")
            git(repo, "update-ref", "refs/remotes/origin/develop", "HEAD")
            files = set(git(repo, "ls-tree", "-r", "--name-only", "origin/develop").split())
            self.assertIn("INCIDENTS.md", self.health.managed_drift(repo, files))

            (repo / "INCIDENTS.md").write_bytes((TPL / "INCIDENTS.md").read_bytes())
            git(repo, "add", "-A")
            git(repo, "commit", "-qm", "canonical")
            git(repo, "update-ref", "refs/remotes/origin/develop", "HEAD")
            files = set(git(repo, "ls-tree", "-r", "--name-only", "origin/develop").split())
            drift = self.health.managed_drift(repo, files)
            self.assertFalse([x for x in drift if x.startswith("INCIDENTS.md")], drift)


if __name__ == "__main__":
    unittest.main(verbosity=2)
